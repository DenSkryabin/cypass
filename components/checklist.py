import streamlit as st
from config.partners import PARTNERS_CONFIG

def render_checklist():
    """Отрисовка чек-листа соответствия критериям статьи 111B Закона о населении."""
    
    st.subheader("I. Доход, трудоустройство и налоги на Кипре")
    
    # -------------------------------------------------------------
    # 1. ТРУДОВОЙ ДОГОВОР
    # -------------------------------------------------------------
    st.markdown("#### 1. Трудовой контракт в компании иностранного интереса (BCS)")
    has_contract = st.radio(
        "Имеется ли действующий трудовой договор с окладом от €2500 брутто?",
        ["Да, контракт подписан", "Нет / Доход ниже €2500 брутто"],
        key="chk_contract"
    )
    if has_contract == "Да, контракт подписан":
        col_c1, col_c2 = st.columns(2)
        with col_c1:
            tax_stamp = st.checkbox("Экземпляр оплачен гербовым сбором (Stamp Duty) в Tax Department?")
            if not tax_stamp:
                st.warning("⚠️ Контракт обязательно должен быть оплачен марками в Tax Department. Отсутствие штампа Stamp Duty влечет штраф и отказ в приеме документов.")
        with col_c2:
            crmd_stamp = st.checkbox("Имеется ли штамп регистрации контракта в Миграционном департаменте (CRMD)?")
            if not crmd_stamp:
                st.warning("⚠️ Отметка CRMD подтверждает легальное трудоустройство в компании иностранного интереса.")
    else:
        part = PARTNERS_CONFIG["legal_consultation"]
        st.error(f"Доход ниже €2500 брутто требует правового аудита структуры начислений (дивиденды, смешанный доход).")
        st.markdown(f"**Партнер:** {part['title']} — {part['desc']} [Подробнее →]({part['link']})")

    # -------------------------------------------------------------
    # 2. SOCIAL INSURANCE
    # -------------------------------------------------------------
    st.markdown("#### 2. Выписка из Фонда социального страхования (Social Insurance)")
    soc_ins = st.radio(
        "Формат выписки об уплате страховых взносов:",
        [
            "Оригинал с «мокрой» синей печатью районного отделения Social Insurance Services (YKE)",
            "Электронная распечатка из системы SISnet (без живой печати)",
            "Выписка отсутствует / есть пробелы в уплате взносов"
        ],
        key="chk_soc_ins"
    )
    if "Электронная" in soc_ins:
        st.warning("❌ Распечатка из SISnet без физической печати не принимается. Обратитесь в районное отделение YKE (Лимассол: Franklin Roosevelt 80; Никосия: Vyronos 7) для проставления печати инспектора.")
    elif "отсутствует" in soc_ins:
        st.error("⚠️ Любые месяцы без взносов вычитаются из срока легального стажа.")
    else:
        st.success("✅ Выписка полностью соответствует регламенту подачи M127.")

    # -------------------------------------------------------------
    # 3. НАЛОГОВЫЕ ДЕКЛАРАЦИИ
    # -------------------------------------------------------------
    st.markdown("#### 3. Персональные налоговые декларации (T.D.1) и подтверждения подачи")
    tax_decl = st.radio(
        "Подавались ли ежегодные декларации в Налоговый департамент Кипра?",
        ["Да, за все годы проживания", "Поданы не за все годы", "Декларации не подавались"],
        key="chk_taxes"
    )
    if tax_decl == "Да, за все годы проживания":
        st.caption("Отметьте налоговые годы, за которые имеются квитанции TAXISnet или T.D.63 (Assessment):")
        cols = st.columns(5)
        cols[0].checkbox("2022", value=True)
        cols[1].checkbox("2023", value=True)
        cols[2].checkbox("2024", value=True)
        cols[3].checkbox("2025", value=True)
        cols[4].checkbox("2026", value=False)
    else:
        st.warning("⚠️ Для подачи на гражданство необходим документ Tax Clearance. Пропущенные декларации можно подать задним числом через налогового консультанта.")

    st.write("---")
    st.subheader("II. Справки об отсутствии судимости (Criminal Record)")

    # -------------------------------------------------------------
    # 4. СПРАВКА ИЗ ПОЛИЦИИ КИПРА
    # -------------------------------------------------------------
    st.markdown("#### 4. Справка от Полиции Республики Кипр")
    pol_cyp = st.radio(
        "Имеется ли оригинал кипрской справки о несудимости?",
        ["Да, оригинал получен", "Нет / В процессе заказа"],
        key="chk_cyp_pol"
    )
    if pol_cyp == "Нет / В процессе заказа":
        st.info("ℹ️ Справка оформляется в Central Police Station или Citizen Service Centre (KEP). Госпошлина €15, срок изготовления — 10–14 дней. Обратите внимание: срок годности справки — строго 6 месяцев.")

    # -------------------------------------------------------------
    # 5. СПРАВКА ИЗ СТРАНЫ ГРАЖДАНСТВА
    # -------------------------------------------------------------
    st.markdown("#### 5. Справка о несудимости из страны гражданства с апостилем")
    pol_orig = st.radio(
        "Имеется ли оригинал справки из страны происхождения с апостилем?",
        ["Да, на руках бумажный оригинал с апостилем", "Нет, требуется оформление"],
        key="chk_orig_pol"
    )
    if pol_orig == "Нет, требуется оформление":
        country_input = st.text_input("Укажите страну гражданства (например, Россия, РФ, Беларусь, Казахстан):", value="РФ")
        country_clean = country_input.strip().lower()

        if any(alias in country_clean for alias in ["рф", "росси", "russia"]):
            part_apo = PARTNERS_CONFIG["police_apostille"]
            st.warning("""
            **Требования к справкам из РФ:**
            - Принимается только бумажная справка МВД РФ на синем гербовом бланке с «мокрой» печатью.
            - Штамп «Апостиль» должен стоять на самом бланке МВД.
            - Электронные справки с Госуслуг и справки из Посольства РФ в Никосии департаментом не принимаются.
            """)
            st.markdown(f"**Партнер:** {part_apo['title']} — {part_apo['desc']} [Оформить заказ →]({part_apo['link']})")
        else:
            st.info(f"Для государства {country_input} требуется апостилирование оригинала либо консульская легализация с последующим присяжным переводом на Кипре.")

    st.write("---")
    st.subheader("III. Экзамены по греческому языку и госустройству")
    
    col_l1, col_l2 = st.columns(2)
    with col_l1:
        lang_res = st.selectbox(
            "Сертификат греческого языка МинОбразования:", 
            ["B1 (ценз: 3 года BCS + 1 год)", "A2 (ценз: 4 года BCS + 1 год)", "Сертификат отсутствует"]
        )
        if "отсутствует" in lang_res:
            part_gr = PARTNERS_CONFIG["greek_courses"]
            st.caption(f"💡 {part_gr['desc']} [Записаться на курс →]({part_gr['link']})")

    with col_l2:
        civic_res = st.selectbox(
            "Экзамен по основам государственного устройства Кипра (≥ 60%):", 
            ["Сдан успешно (сертификат получен)", "Готовлюсь к сдаче", "Еще не сдавался"]
        )
        if civic_res != "Сдан успешно (сертификат получен)":
            part_civ = PARTNERS_CONFIG["civic_exam"]
            st.caption(f"💡 {part_civ['desc']} [Открыть базу вопросов →]({part_civ['link']})")